def emit(schema, table, per, cmds, cols, fkmap, colsmap, enums, unique_cols, checks=None, cuniques=None, relchecks=None, compfks=None):
    S = _seed_plan(schema, table, per, cmds, cols, fkmap, colsmap, enums, unique_cols, checks, cuniques, relchecks, compfks)
    q = S["q"]; cls = f"test_{table}"
    seed = S["seed"]; total_rows = S["total_rows"]; insert_plan = S["insert_plan"]
    nobody_ins = S["nobody_ins"]; primary = S["primary"]; pkind = S["pkind"]
    rowlinked = S["rowlinked"]; fill = S["fill"]; foreign_val = S["foreign_val"]

    out = [f"""-- GENERATED by testgen.rls (command-aware, deep-seeding) from {q}. Do not edit.
{_PGTAP_ENSURE}
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA {schema} TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA {schema} TO authenticated;
GRANT SELECT ON ALL TABLES IN SCHEMA {schema} TO anon;
DROP SCHEMA IF EXISTS {cls} CASCADE;
CREATE SCHEMA {cls};
CREATE FUNCTION {cls}._seed() RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  SET LOCAL ROLE service_role;
  DELETE FROM {q};
{seed}
END $$;
"""]
    n = [0]
    def fn(name, decl, actsql, cj, asserts, role="authenticated"):
        n[0] += 1
        a = "\n".join(f"  RETURN NEXT {x};" for x in asserts)
        return f"""CREATE FUNCTION {cls}.test_{n[0]:02d}_{name}() RETURNS SETOF TEXT LANGUAGE plpgsql AS $$
DECLARE runner text := current_user; {decl}
BEGIN
  PERFORM {cls}._seed();
  PERFORM set_config('request.jwt.claims', '{cj}', true);
  SET LOCAL ROLE {role};
{actsql}
  EXECUTE format('SET LOCAL ROLE %I', runner);
{a}
END $$;
"""
    cj = lambda c: json.dumps(c["claims"])
    NB = json.dumps({"sub": NOBODY, "role": "authenticated", "exp": FUTURE_EXP})

    for cmd in cmds:
        pc = per[cmd]; classes = [c for c in pc["classes"] if c["handled"]]
        if cmd == "SELECT":
            for c in classes:
                exp = total_rows if not c["rowlinked"] else 1
                out.append(fn(f"select_b{c['idx']}", "k int;", f"  SELECT count(*) INTO k FROM {q};", cj(c),
                              [f"is(k, {exp}, 'SELECT branch {c['idx']}: {'sees all (open/grant)' if not c['rowlinked'] else 'sees only its own row'}')"]))
            anon_exp = total_rows if pc.get("anon_open") else 0
            out.append(fn("select_anon", "k int;", f"  SELECT count(*) INTO k FROM {q};", "",
                          [f"is(k, {anon_exp}, 'SELECT: anon sees {('all (public policy)' if pc.get('anon_open') else 'nothing')}')"], role="anon"))
            if not pc["open"] and classes:
                out.append(fn("select_nobody_denied", "k int;", f"  SELECT count(*) INTO k FROM {q};", NB, ["is(k, 0, 'SELECT: unauthorized sees nothing')"]))
        elif cmd == "INSERT":
            for c in classes:
                if c["idx"] in insert_plan:
                    icl, iv = insert_plan[c["idx"]]
                    out.append(fn(f"insert_b{c['idx']}_ok", "got text;", f"  BEGIN INSERT INTO {q}({', '.join(_qi(c) for c in iv)}) VALUES ({', '.join(iv.values())}); got:='OK'; EXCEPTION WHEN others THEN got:=SQLSTATE; END;", icl,
                                  [f"is(got, 'OK', 'INSERT branch {c['idx']}: authorized may write')"]))
            if not pc["open"] and nobody_ins:
                out.append(fn("insert_nobody_denied", "got text;", f"  BEGIN INSERT INTO {q}({', '.join(_qi(c) for c in nobody_ins)}) VALUES ({', '.join(nobody_ins.values())}); got:='NO ERROR'; EXCEPTION WHEN insufficient_privilege THEN got:=SQLSTATE; WHEN others THEN got:=SQLSTATE; END;", NB,
                              ["is(got, '42501', 'INSERT: unauthorized cannot write')"]))
        elif cmd == "UPDATE" and (upd := next(((nn0, tt0) for (nn0, tt0, c0, h0) in cols if nn0 not in {x for cc in rowlinked for x in cc['rowseed']} and not h0), None)):
            for c in classes:
                out.append(fn(f"update_b{c['idx']}_ok", "m int;", f"  UPDATE {q} SET {_qi(upd[0])}={fill(upd[1])}; GET DIAGNOSTICS m=ROW_COUNT;", cj(c),
                              [f"cmp_ok(m, '>=', 1, 'UPDATE branch {c['idx']}: authorized may update its rows')"]))
                if c["rowlinked"] and c["scalar_link"] and c["fk_val"] and c["scalar_link"] not in unique_cols:
                    out.append(fn(f"update_b{c['idx']}_reassign_denied", "got text;", f"  BEGIN UPDATE {q} SET {_qi(c['scalar_link'])}='{FOREIGN}'; got:='NO ERROR'; EXCEPTION WHEN insufficient_privilege THEN got:=SQLSTATE; WHEN others THEN got:=SQLSTATE; END;", cj(c),
                                  [f"is(got, '42501', 'UPDATE branch {c['idx']}: cannot move row out of scope')"]))
            if classes:
                out.append(fn("update_nobody_denied", "m int;", f"  UPDATE {q} SET {_qi(upd[0])}={fill(upd[1])}; GET DIAGNOSTICS m=ROW_COUNT;", NB, ["is(m, 0, 'UPDATE: unauthorized affects 0 rows')"]))
        elif cmd == "DELETE":
            for c in classes:
                out.append(fn(f"delete_b{c['idx']}_ok", "m int;", f"  DELETE FROM {q}; GET DIAGNOSTICS m=ROW_COUNT;", cj(c),
                              [f"cmp_ok(m, '>=', 1, 'DELETE branch {c['idx']}: authorized may delete its rows')"]))
            if classes:
                out.append(fn("delete_nobody_denied", "m int;", f"  DELETE FROM {q}; GET DIAGNOSTICS m=ROW_COUNT;", NB, ["is(m, 0, 'DELETE: unauthorized affects 0 rows')"]))
    out.append(f"\nSELECT * FROM runtests('{cls}'::name);\n")
    return "".join(out)



def emit_flat(schema, table, per, cmds, cols, fkmap, colsmap, enums, unique_cols, checks=None, cuniques=None, relchecks=None, compfks=None, helpers=True, grants_map=None, conn=None, implicit_deny=False, obs_out=None, notes_out=None, sanctioned=None):
    """Native Supabase FLAT pgTAP form: begin; plan(N); inline AAA; finish(); rollback.

    helpers=True (DEFAULT): tests read natively — tests.create_supabase_user / authenticate_as /
      clear_authentication for identity, with tests.get_supabase_uid() substituted into the seed's
      owner columns. Custom-claim (tenant/RBAC) classes keep a direct set_config (no helper exists).
      Requires the tests.* helpers (basejump, or the rlsautotest offline shim emitted in 000-setup).
    helpers=False (--no-helpers): fully self-contained — inline set_config + SET LOCAL ROLE, ensures
      pgtap, no 000-hook dependency; one file runs standalone."""
    if conn is None:
        # F10: the old DB-less "derive" battery emitted GUESSED assertions (never probed). Removed:
        # every emitted assertion is observed against the real database first — never fabricated.
        raise ValueError("emit_flat requires a live database connection (--db-url or PG* env): "
                         "tests are probe-and-baked, not guessed")
    _authp = auth_profile(conn.cursor(), schema)   # catalog-discovered client-role model (authenticated / unauth / optional bypass)
    # MB-9b: which CONSTRAINED probed slots (the authenticated identity + the unauth role) themselves carry
    # BYPASSRLS? If so, probing as them sees every row regardless of policy -> their matrix cells are baked
    # UNRELIABLE (never a green), by the guard in ProbeBaker.read_assert/write_assert. Empty for every
    # normal schema (only service_role bypasses), so the corpus stays byte-identical. service_role is NOT
    # passed in -- its bypass is the point of that row.
    _bypass_probed = probed_bypassrls(conn.cursor(), ["authenticated", _authp["unauth"]])
    no_probe = getattr(conn, "_rlsa_no_probe", False)   # MB-10 --no-probe: emit only the no-probe (structural) tests
    S = _seed_plan(schema, table, per, cmds, cols, fkmap, colsmap, enums, unique_cols, checks, cuniques, relchecks, compfks, conn=conn)
    q = S["q"]; seed = S["seed"]; total_rows = S["total_rows"]
    insert_plan = S["insert_plan"]; nobody_ins = S["nobody_ins"]; fill = S["fill"]
    rowlinked = S["rowlinked"]
    # Membership EXISTS with an internal opaque-fn conjunct (e.g. `m.room_topic = realtime.topic()`): mock the
    # fn to the seeded membership-scope value so the member row satisfies it. Prepend to `seed` so every
    # (re)seed installs it as the privileged role (wiring proof — the fn's own logic stays unverified -> footgun).
    _seed_fn_mock = False
    if conn is not None:
        _fm, _seen = [], set()
        for _cmd0 in per:
            for _c0 in per[_cmd0]["classes"]:
                for _mk0 in _c0.get("fn_mocks", []):
                    _sig0 = _opaque_fn_sig(conn, _mk0["node"])
                    if not _sig0:
                        continue
                    _st0 = (f"CREATE OR REPLACE FUNCTION {_sig0['q']}({_sig0['args']}) RETURNS {_sig0['rettype']} "
                            f"LANGUAGE sql AS $$ SELECT '{_mk0['value']}'::{_sig0['rettype']} $$")
                    if _st0 not in _seen:
                        _seen.add(_st0); _fm.append(_st0)
        if _fm:
            seed = ";\n".join(_fm) + ";\n" + seed
            _seed_fn_mock = True
    # Defect B: a logged-in identity IS a real auth.users row. In no-helpers mode the acting uid is set purely
    # via the JWT claim and is not otherwise inserted, so a trigger/FK that references auth.users (e.g. a
    # bootstrap trigger inserting a membership FK'd to auth.users) fails the probe with a foreign-key error.
    # Seed the synthetic identity subs so those resolve. ON CONFLICT keeps it idempotent; the battery is rolled back.
    if conn is not None:
        try:
            _uc = conn.cursor(); _uc.execute("SELECT to_regclass('auth.users')")
            if _uc.fetchone()[0] is not None:
                _idsubs = sorted({NOBODY, RIVAL_SUB, INS, *CV, *MV}
                                 | ({MULTI_SUB} if S.get("multi", {}).get("on") else set()))   # INS: the fresh-identity INSERT's acting user may FK auth.users too; MULTI_SUB only when the 2-tenant member is seeded (keeps non-membership suites byte-identical)
                seed = ";\n".join(f"INSERT INTO auth.users(id) VALUES ('{s}') ON CONFLICT DO NOTHING" for s in _idsubs) + ";\n" + seed
        except Exception:
            pass
    cj = lambda c: json.dumps(c["claims"])
    NB = json.dumps({"sub": NOBODY, "role": "authenticated", "exp": FUTURE_EXP})


    # helper-mode: create test users whose uid IS our seed uuid, so NO substitution is needed — the seed
    # stays literal and authenticate_as('u_N') returns exactly that uuid as auth.uid(). Pure-owner classes
    # (incl. owner/folder/membership/nobody) use authenticate_as; custom-claim (tenant/RBAC) keep set_config.
    body, n, sp = [], [0], [0]
    # F1/F8: the closure-captured locals now live on a typed EmitContext; the identity/description
    # helpers are its methods and the probe-then-bake discipline is the ProbeBaker (see structs/probe).
    ctx = EmitContext(schema=schema, table=table, per=per, cmds=cmds, cols=cols, fkmap=fkmap,
                      colsmap=colsmap, enums=enums, unique_cols=unique_cols, checks=checks,
                      cuniques=cuniques, relchecks=relchecks, compfks=compfks, helpers=helpers,
                      gmap=grants_map or {}, conn=conn, q=q, S=S, seed=seed, total_rows=total_rows,
                      claim_style=_authp.get("claim_style", "json"),
                      unauth_role=_authp["unauth"], emit_service_role=(_authp["service_role"] is not None),
                      service_role_name=(_authp["service_role"] or "service_role"),
                      bypass_probed=_bypass_probed, sanctioned_unreliable=sanctioned,
                      insert_plan=insert_plan, nobody_ins=nobody_ins, fill=fill, rowlinked=rowlinked,
                      seed_fn_mock=_seed_fn_mock, NB=NB, body=body, n=n,
                      observations=(obs_out if obs_out is not None else []),
                      branch_nt=(notes_out if notes_out is not None else []))
    baker = ProbeBaker(ctx)
    umap = ctx.umap
    ident = ctx.ident
    # restore the seeded precondition after a mutating test by RE-SEEDING (not SAVEPOINT/ROLLBACK):
    # real pgTAP keeps its test counter in txn-local state, and ROLLBACK TO SAVEPOINT would unwind it
    # (-> "planned N ran M" under pg_prove). Re-seeding isolates without touching the counter; the outer
    # ROLLBACK still discards everything at the end.
    seed_emit = ctx.seed_emit = _wrap_seed(seed)   # P2b: fault-tolerant arrange for the EMITTED file (raw `seed` still used for the live probe)
    # Seed as an identity-NEUTRAL privileged role: RESET ROLE drops the Postgres role but NOT the JWT claim,
    # so auth.uid() would still return the last probed identity and an ownership-on-insert trigger (e.g.
    # supabase_rbac's on_group_created) would attribute the seeded row to it. Clear the claim so auth.uid() is NULL.
    # When the table has AUX/scope tables, clear them BEFORE `DELETE FROM q`: if q is an aux table's FK
    # PARENT (tenancy.orgs with memberships.org_id -> orgs.id, mtt.teams with team_members.team_id ->
    # teams.id), the q-first DELETE violates the FK and -- raw, inside the pgTAP transaction -- aborted the
    # rest of the file (pg_prove "planned N ran M"). The delete block is _rlsa_try-wrapped like the
    # header's, so an unrelated FK reference degrades to a loud failing count, never a mid-file abort.
    # Tables with NO aux keep the exact old raw form (emitted bytes unchanged).
    _aux_ts = S.get("aux_tables", [])
    if _aux_ts:
        _redel = _wrap_seed("".join(f"DELETE FROM {_qt(t)};\n" for t in _aux_ts) + f"DELETE FROM {q}")
        reseed = ctx.reseed = f"RESET ROLE;\nSELECT set_config('request.jwt.claims', '', true);\n{_redel}\n{seed_emit}"
    else:
        reseed = ctx.reseed = f"RESET ROLE;\nSELECT set_config('request.jwt.claims', '', true);\nDELETE FROM {q};\n{seed_emit}"
    read_test, mut_test = baker.read_test, baker.mut_test
    desc = ctx.desc
    # Real effective grants for the client roles (NOT re-granted): we PROVE actual access, never assume it.
    geff = ctx.geff
    # pick a plain writable column for the denial UPDATE (avoid identity/generated cols -> parse error before the ACL check)
    _wcol = next((nn0 for (nn0, tt0, c0, h0) in cols
                  if nn0 not in {x for cc in rowlinked for x in cc['rowseed']} and not h0),
                 (cols[0][0] if cols else None))
    ctx.deny_stmt = {"SELECT": f"SELECT 1 FROM {q}",
                     "INSERT": f"INSERT INTO {q} DEFAULT VALUES",
                     "UPDATE": (f"UPDATE {q} SET {_wcol}={_wcol}" if _wcol else None),
                     "DELETE": f"DELETE FROM {q}"}
    deny = baker.deny
    if conn is not None:   # PROBE path: observe the REAL outcome of each identity x command on the copy, then bake it
        # aux tables cleared BEFORE q for the same FK-parent reason as the reseed above: the probe's
        # per-statement savepoints would swallow a failing q-first DELETE, silently leaving stale
        # committed rows in the counts.
        _adel = "".join(f"DELETE FROM {_qt(t)};\n" for t in S.get("aux_tables", []))
        arrange_stmts = [s for s in _split_statements(f"{_adel}DELETE FROM {q};\n{seed}") if s.strip()]
        _fk_cols = set(fkmap.get(f"{schema}.{table}", {}))   # avoid FK cols: SET fk=val triggers an RI check (parent access), not the table's own UPDATE perm
        _rowseed = {x for cc in rowlinked for x in cc['rowseed']}
        # Columns referenced by ANY policy on the table (USING + WITH CHECK). SETting one of these would
        # test scope-movement or the WITH CHECK value-space, NOT the plain UPDATE grant -> exclude them so we
        # change a POLICY-NEUTRAL column. No fallback to FK/unique/policy columns (those SETs fail for reasons
        # unrelated to RLS and would mis-bake as denials); if none is neutral, upd_col stays None and UPDATE is
        # honestly "not tested - no neutral column" (surfaced as a note by the report).
        _policy_cols = set()
        try:
            # F6: read the policy ASTs, not a regex over the policy text — a column NAME inside a
            # string literal/comment no longer wrongly disqualifies a neutral column, and a quoted
            # or oddly-cased identifier can't slip past. Same demand as before: every real column
            # of THIS table referenced anywhere in any policy's USING or WITH CHECK.
            _pcur = conn.cursor()
            _pcur.execute("SELECT qual, with_check FROM pg_policies WHERE schemaname=%s AND tablename=%s", (schema, table))
            _ctypes = {nn0: tt0 for (nn0, tt0, _c, _h) in cols}
            for (_pq, _pw) in _pcur.fetchall():
                for _pe in (_pq, _pw):
                    if not _pe:
                        continue
                    _pn = _where(_pe)
                    if _pn is not None:
                        _policy_cols.update(_expr_cols(_pn, _ctypes))
        except Exception:
            _policy_cols = set()
        # A plain DEFAULT does NOT make a column unsettable — only IDENTITY / GENERATED columns can't be the
        # target of SET. (h0 = "has default OR identity" was too broad: it left ownership tables like
        # rbac.members — whose only non-key columns, roles/metadata, carry defaults — with no testable UPDATE.)
        _unsettable = set()
        try:
            _gcur = conn.cursor()
            _gcur.execute("""SELECT a.attname FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid
                JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=%s AND c.relname=%s
                AND a.attnum>0 AND NOT a.attisdropped AND (a.attidentity <> '' OR a.attgenerated <> '')""", (schema, table))
            _unsettable = {r[0] for r in _gcur.fetchall()}
        except Exception:
            _unsettable = set()
        upd_col = next(((nn0, tt0) for (nn0, tt0, c0, h0) in cols
                        if nn0 not in _unsettable and nn0 not in _fk_cols and nn0 not in unique_cols
                        and nn0 not in _rowseed and nn0 not in _policy_cols), None)
        # No policy-neutral column at all (key-and-scope-only tables like wcard.events: PK + owner)?
        # Fall back to a SELF-ASSIGNMENT column: `SET col = col` changes nothing and moves no row
        # between scopes, but Postgres still enforces the UPDATE privilege and re-evaluates
        # USING/WITH CHECK — exactly what the UPDATE cell claims to measure. (An unchanged FK skips
        # the RI re-check; identity/generated columns are still excluded.) MB-5: a UNIQUE column is now
        # allowed here -- `SET col = col` assigns the row its OWN current value, which cannot collide
        # with another row, so the unique constraint is not violated. This tests the last shape that
        # previously fell to a "-" dash (updcheck.t4: identity PK + a UNIQUE policy column). A CLS
        # denial on the column surfaces as an observed 42501 (a real denial), never a false grant.
        _upd_self = None if upd_col else next((nn0 for (nn0, tt0, c0, h0) in cols
                                               if nn0 not in _unsettable), None)
        ctx.arrange_stmts, ctx.fk_cols, ctx.upd_col = arrange_stmts, _fk_cols, upd_col
        _upd_val = ctx.upd_val       # CHECK-satisfying SET literal (see EmitContext.upd_val)
        pident = ctx.pident
        identities = ctx.identities  # who-labels feed the baked descriptions and the report parser
        udfs = ctx.udfs = _policy_bool_udfs(conn, schema, table)   # opaque boolean fns the policies delegate to (mock fallback)
        coltypes = ctx.coltypes = {nn0: tt0 for (nn0, tt0, c0, h0) in cols}

        _cur = conn.cursor()   # every command that HAS a policy (analyzer's cmds may omit opaque-fn ones)
        _cur.execute("SELECT DISTINCT cmd FROM pg_policies WHERE schemaname=%s AND tablename=%s", (schema, table))
        _pol = set()
        for (_cm,) in _cur.fetchall():
            _pol |= set(_CMDS4) if _cm == "ALL" else ({_cm} if _cm in _CMDS4 else set())
        for cmd in [c for c in _CMDS4 if c in (set(cmds) | _pol)]:
            if no_probe:
                continue   # MB-10 --no-probe: skip EVERY row-level battery (all probe-based) -> those cells stay NOT tested
            _all_cls = per.get(cmd, {}).get("classes", [])
            classes = [c for c in _all_cls if c["handled"]]
            # MIXED case: a classifiable policy AND a SEPARATE opaque-function policy OR'd together (permissive).
            # The classifiable branch is probed below; without this the function branch would be left shadowed
            # (NOT_TESTABLE, untested). Mock-wire it too so the function branch is proven to grant/deny, and so
            # the report flags + highlights the mocking on those cells.
            _shadowed_fn = bool(classes) and bool(udfs) and any((not cc.get("handled")) and "function" in (cc.get("reason") or "") for cc in _all_cls)
            ctx.classes = classes
            handled = False
            for _strategy in REGISTRY:   # the old if/elif dispatch ladder, now the ordered strategy registry (F1)
                _res = _strategy(ctx, baker, cmd)   # strategies guard themselves on ctx.classes; CONTINUE = additive (F5)
                if _res == HANDLED:
                    handled = True
                    break
                if _res == AUGMENT:      # wiring tests emitted; the identity battery below still runs
                    break
            # BL-1 generalized -- the OBLIGATION ROUTER: a classifiable branch handled this command, but OTHER
            # min-terms carry novel (unclassified) atoms. Route EVERY unhandled branch, node-scoped, through
            # the fallback chain: the general solver first, then the relational-state DB-oracle floor. A branch
            # that delegates to an opaque boolean fn is excluded here (the mock wiring above owns it, and its
            # mocking is already flagged); a branch that still ends up unwitnessed is RECORDED (ctx.branch_nt)
            # so the report can say "partially tested" instead of hiding the gap behind a green sibling cell.
            if classes:
                for _uc in [c for c in _all_cls if not c.get("handled")]:
                    _ra = _uc.get("raw_atoms")
                    _nd = None
                    if _ra:
                        _nd = _ra[0] if len(_ra) == 1 else {"BoolExpr": {"boolop": "AND_EXPR", "args": _ra}}
                    _is_fn_branch = _nd is not None and _calls_udf(_nd, udfs)
                    if _is_fn_branch:
                        # UDF branch: expand the function body into an effective predicate (witness
                        # HINTS only -- the probe still runs the real policy calling the real fn) and
                        # route the substituted node like any other branch. Unexpandable -> stay on
                        # the mock wiring path (already emitted + flagged above).
                        _nd = _expand_udf_calls(_nd, conn.cursor())
                    # MB-6: a restrictive policy is AND'd onto this permissive branch by Postgres. raw_atoms
                    # carries only the PERMISSIVE min-term, so a witness solved from _nd alone can violate the
                    # restrictive check -> the REAL policy denies -> the branch would fall to PARTIALLY TESTED
                    # (sound, coverage lost). Conjoin the restrictive predicate(s) so the solver seeds them too.
                    # A restrictive conjunct that itself delegates to an opaque fn is expanded (witness hints);
                    # if it can't be expanded, it is dropped from the obligation (the branch just degrades to
                    # the pre-MB-6 coverage for that case -- still sound, the probe runs the real restrictive fn).
                    _rst = _uc.get("raw_restrict")
                    if _nd is not None and _rst:
                        _rst_nodes = []
                        for _rn in _rst:
                            _rn2 = _expand_udf_calls(_rn, conn.cursor()) if _calls_udf(_rn, udfs) else _rn
                            if _rn2 is not None and not _calls_udf(_rn2, udfs):
                                _rst_nodes.append(_rn2)
                        if _rst_nodes:
                            _nd = {"BoolExpr": {"boolop": "AND_EXPR", "args": [_nd] + _rst_nodes}}
                    _rescued = False
                    if _nd is not None:
                        _rescued = solve_emit(ctx, baker, cmd, node=_nd)
                        if not _rescued:
                            _rescued = relstate_emit(ctx, baker, cmd, node=_nd)
                    if _is_fn_branch:
                        continue   # never a branch_nt entry: the wiring proof + mock footgun note cover the fn branch
                    if not _rescued:
                        _rr = _uc.get("reason") or "branch could not be parsed"
                        ctx.branch_nt.append((cmd, _uc.get("src_policy"), _rr))
                        body.append(f"-- PARTIALLY TESTED: {cmd} policy branch [{_uc.get('src_policy') or '?'}] left unwitnessed -> {_rr}")
