def _shim_sql(prof=None):
    """MB-11: the offline tests.* shim with its CLIENT-ROLE VOCABULARY taken from the schema's DISCOVERED
    role model (auth_profile) instead of hardcoded to Supabase's anon / service_role. A conventional
    unauthenticated role (anon or anonymous) is used verbatim; anything else -- or no profile -- falls back
    to 'anon' (so a mis-discovered login role never rewrites the shim). The RLS-bypass helper is emitted
    against the discovered bypass role when the database HAS one; a provider without one (Neon has no
    service_role) gets a loud-failing stub, so a hand-written call errors clearly instead of on a missing
    role. For a standard Supabase role model -- or prof=None -- every branch is skipped and this returns
    _SHIM verbatim, byte-identical to before. Targeted string edits keep the (long) shim body in ONE place."""
    _u = (prof or {}).get("unauth")
    unauth = _u if _u in ("anon", "anonymous") else "anon"
    # The bypass helper reflects whether the PROVIDER has an RLS-bypass role, not whether one is granted in
    # THIS schema (auth_profile.service_role is schema-scoped -> None wherever service_role holds no local
    # grant, though a Supabase DB still HAS the role). So drop it only for a provider with none (Neon), and
    # otherwise keep 'service_role' (or a discovered rename). This keeps every Supabase schema byte-identical.
    if prof and prof.get("flavor") == "neon":
        service = None
    else:
        service = (prof or {}).get("service_role") or "service_role"
    s = _SHIM
    if unauth != "anon":
        s = s.replace("GRANT USAGE ON SCHEMA tests TO anon,", f"GRANT USAGE ON SCHEMA tests TO {unauth},")
        s = s.replace("BEGIN PERFORM set_config('role', 'anon', true);",
                      f"BEGIN PERFORM set_config('role', '{unauth}', true);")
    if not service:
        s = s.replace(", service_role;", ";")   # no RLS-bypass role -> drop it from the tests-schema grant
        s = s.replace("BEGIN PERFORM set_config('role', 'service_role', true); PERFORM set_config('request.jwt.claims', null, true); END",
                      "BEGIN RAISE EXCEPTION 'this database has no RLS-bypass (service_role) role'; END")
    elif service != "service_role":
        s = s.replace(", service_role;", f", {service};")
        s = s.replace("set_config('role', 'service_role', true)", f"set_config('role', '{service}', true)")
    return s



_PGTAP_ENSURE = r"""-- Make pgTAP available with ZERO setup: use the real extension if installed; otherwise load a minimal,
-- TAP-compatible shim. The shim is created ONLY when pgTAP is absent, so a real install (e.g. on Supabase)
-- is always preferred and never shadowed. Numbering uses a sequence so it survives SAVEPOINT rollbacks.
DO $rlsa$
BEGIN
  BEGIN CREATE EXTENSION IF NOT EXISTS pgtap; EXCEPTION WHEN OTHERS THEN NULL; END;
  IF to_regprocedure('plan(integer)') IS NULL THEN
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public._rlsa_num() RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER AS $q$ BEGIN RETURN nextval('__rlsa_tapno'); END $q$ $b$;
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public._rlsa_ok(boolean, text) RETURNS text LANGUAGE sql AS $q$ SELECT (CASE WHEN $1 THEN 'ok ' ELSE 'not ok ' END) || public._rlsa_num() || ' - ' || coalesce($2,'') $q$ $b$;
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public.plan(integer) RETURNS text LANGUAGE plpgsql SECURITY DEFINER AS $q$ BEGIN EXECUTE 'DROP SEQUENCE IF EXISTS pg_temp.__rlsa_tapno'; EXECUTE 'CREATE TEMP SEQUENCE __rlsa_tapno'; RETURN '1..'||$1; END $q$ $b$;
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public.finish() RETURNS SETOF text LANGUAGE plpgsql AS $q$ BEGIN RETURN; END $q$ $b$;
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public.is(anyelement, anyelement, text) RETURNS text LANGUAGE sql AS $q$ SELECT public._rlsa_ok($1 IS NOT DISTINCT FROM $2, $3) $q$ $b$;
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public.lives_ok(text, text) RETURNS text LANGUAGE plpgsql AS $q$ BEGIN EXECUTE $1; RETURN public._rlsa_ok(true, $2); EXCEPTION WHEN OTHERS THEN RETURN public._rlsa_ok(false, $2); END $q$ $b$;
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public.throws_ok(text, text, text, text) RETURNS text LANGUAGE plpgsql AS $q$ BEGIN EXECUTE $1; RETURN public._rlsa_ok(false, $4); EXCEPTION WHEN OTHERS THEN RETURN public._rlsa_ok(SQLSTATE = $2, $4); END $q$ $b$;
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public.is_empty(text, text) RETURNS text LANGUAGE plpgsql AS $q$ DECLARE r record; f boolean := false; BEGIN FOR r IN EXECUTE $1 LOOP f := true; EXIT; END LOOP; RETURN public._rlsa_ok(NOT f, $2); END $q$ $b$;
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public.isnt_empty(text, text) RETURNS text LANGUAGE plpgsql AS $q$ DECLARE r record; f boolean := false; BEGIN FOR r IN EXECUTE $1 LOOP f := true; EXIT; END LOOP; RETURN public._rlsa_ok(f, $2); END $q$ $b$;
    EXECUTE $b$ CREATE OR REPLACE FUNCTION public.fail(text) RETURNS text LANGUAGE sql AS $q$ SELECT public._rlsa_ok(false, $1) $q$ $b$;
  END IF;
END
$rlsa$;
-- Seed-swallow helper: runs an arrange statement and SWALLOWS any error (in its own subtransaction) so a
-- failing seed for a genuinely un-seedable table does NOT abort the whole pgTAP file -> the table stays empty
-- and the baked UNRELIABLE assertion still runs and prints a clean `not ok` line (instead of an opaque abort).
CREATE OR REPLACE FUNCTION public._rlsa_try(sql text) RETURNS void LANGUAGE plpgsql AS $rt$ BEGIN EXECUTE sql; EXCEPTION WHEN OTHERS THEN NULL; END $rt$;"""



